async function seedCountries() {
  try {
    console.log('🌍 Seeding countries...');

    // Check if countries already exist
    const existingCount = await Country.countDocuments().catch((e) => { console.log(e) });
    if (existingCount > 0) {
      console.log(`🗑️  ${existingCount} countries already exist. Skipping seeding.`);
      return { skipped: true, count: existingCount };
    }

    // Validate data before insertion
    if (!Array.isArray(countries) || countries.length === 0) {
      throw new Error('Invalid countries data: must be non-empty array');
    }

    // Clear existing countries (safety measure)
    await Country.deleteMany({}).catch((e) => { console.log(e) });

    // Insert new countries with batch processing
    const batchSize = 50;
    const results = [];

    for (let i = 0; i < countries.length; i += batchSize) {
      const batch = countries.slice(i, i + batchSize);
      try {
        const batchResult = await Country.insertMany(batch, { ordered: false });
        if (batchResult) results.push(...batchResult);
      } catch (batchError) {
        console.warn(`⚠️  Batch ${Math.floor(i / batchSize) + 1} had issues:`, batchError.message);
        if (batchError.insertedDocs) {
          results.push(...batchError.insertedDocs);
        }
      }
    }

    console.log(`✅ Successfully seeded ${results.length} countries`);
    return { success: true, count: results.length, data: results };

  } catch (error) {
    console.error('❌ Error seeding countries:', error.message);
    // Return error info instead of throwing to prevent crash
    return { success: false, error: error.message, count: 0 };
  }
}

